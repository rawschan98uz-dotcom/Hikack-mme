/**
 * Writes src/styles/dark-palette.css: how the ready-made Tailwind colours used in the pages look in the
 * dark theme (light tints become dim glows, dark text becomes light). `npm run build` runs it first,
 * so new colour classes get their dark look by themselves.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import colors from 'tailwindcss/colors.js';

const SRC = new URL('../src/', import.meta.url).pathname;
const OUT = join(SRC, 'styles/dark-palette.css');
const NEUTRALS = ['slate', 'gray', 'zinc', 'neutral', 'stone'];
const VARIANTS = { '': '', 'hover:': ':hover', 'focus:': ':focus', 'active:': ':active', 'disabled:': ':disabled' };

function files(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return files(path);
    return /\.(vue|ts)$/.test(name) ? [path] : [];
  });
}

const CLASS = /(?<![\w-])((?:hover:|focus:|active:|disabled:)?)(!?)(bg|text|border|ring)-((?:[a-z]+)-(?:50|[1-9]00|950)|white|black)(?:\/(\d{1,3}))?(?![\w-])/g;
const found = new Set();
for (const file of files(SRC)) {
  if (file.includes('/styles/')) continue;
  for (const m of readFileSync(file, 'utf8').matchAll(CLASS)) found.add(m[0]);
}

function rgb(hex) {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(' ');
}

function escape(cls) {
  return cls.replace(/[:/.!]/g, (c) => `\\${c}`);
}

/** The dark-theme colour for one class, or null when it already reads well on a dark page. */
function darkValue(prop, colorName, shade, alphaMod) {
  const mod = alphaMod == null ? 1 : alphaMod / 100;
  if (colorName === 'white') {
    if (prop === 'bg') return `rgb(var(--c-card) / ${mod})`;
    if (prop === 'border' || prop === 'ring') return `rgb(var(--c-line) / ${mod})`;
    return null;
  }
  if (colorName === 'black') return null;
  const family = colors[colorName];
  if (!family || typeof family !== 'object') return null;
  const n = Number(shade);

  if (NEUTRALS.includes(colorName)) {
    if (prop === 'bg') {
      if (n <= 50) return `rgb(var(--c-canvas) / ${mod})`;
      if (n <= 100) return `rgb(var(--c-line) / ${0.55 * mod})`;
      if (n <= 300) return `rgb(var(--c-line) / ${mod})`;
      return null;
    }
    if (prop === 'text') {
      if (n >= 800) return 'rgb(var(--c-text))';
      if (n >= 600) return 'rgb(var(--c-secondary))';
      if (n >= 400) return 'rgb(var(--c-icon))';
      return null;
    }
    if (n <= 200) return `rgb(var(--c-line) / ${mod})`;
    if (n <= 400) return `rgb(var(--c-line-strong) / ${mod})`;
    return null;
  }

  const glow = rgb(family[500]);
  if (prop === 'bg') {
    if (n >= 500) return null; // solid buttons and badges with white text stay as they are
    const base = { 50: 0.1, 100: 0.16, 200: 0.24, 300: 0.32, 400: 0.4 }[n];
    return `rgb(${glow} / ${Math.max(+(base * mod).toFixed(3), 0.06)})`;
  }
  if (prop === 'text') {
    if (n < 500) return null;
    const lighter = n >= 800 ? 200 : n >= 600 ? 300 : 400;
    return `rgb(${rgb(family[lighter])})`;
  }
  // border / ring
  if (n >= 500) return null;
  return `rgb(${glow} / ${(n <= 200 ? 0.35 : 0.5) * mod})`;
}

const PROPERTY = { bg: 'background-color', text: 'color', border: 'border-color', ring: '--tw-ring-color' };
const rules = [];
for (const cls of [...found].sort()) {
  const m = /^((?:hover:|focus:|active:|disabled:)?)(!?)(bg|text|border|ring)-(?:([a-z]+)-(\d+)|(white|black))(?:\/(\d+))?$/.exec(cls);
  if (!m) continue;
  const [, variant, important, prop, name, shade, plain, alpha] = m;
  const value = darkValue(prop, plain ?? name, shade, alpha == null ? null : Number(alpha));
  if (!value) continue;
  rules.push(`:root[data-theme='dark'] .${escape(cls)}${VARIANTS[variant]} { ${PROPERTY[prop]}: ${value}${important ? ' !important' : ''}; }`);
}

writeFileSync(
  OUT,
  `/* Generated by tools/gen-dark-theme.mjs — do not edit by hand. */\n${rules.join('\n')}\n`,
);
console.log(`dark-palette.css: ${rules.length} rules`);
